let currentLang = localStorage.getItem('semalt_lang') || 'en';
let favorites = JSON.parse(localStorage.getItem('semalt_favs') || '[]');
let customTools = JSON.parse(localStorage.getItem('semalt_custom') || '[]');
let ratings = JSON.parse(localStorage.getItem('semalt_ratings') || '{}');
let currentActiveTab = 'explore';
let currentCategory = 'AI';
let windowLastFetchedItems = [];

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('semalt_lang', lang);
    
    ['en', 'ar', 'uk'].forEach(l => {
        const btn = document.getElementById(`btnLang${l.charAt(0).toUpperCase() + l.slice(1)}`);
        if(btn) {
            if(l === lang) {
                btn.className = "px-2 py-1 rounded-lg text-xs font-bold transition bg-indigo-600 text-white cursor-pointer shadow";
            } else {
                btn.className = "px-2 py-1 rounded-lg text-xs font-bold transition text-slate-400 hover:text-white cursor-pointer";
            }
        }
    });

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if(translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if(translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    if(windowLastFetchedItems.length > 0) {
        const isDefault = windowLastFetchedItems.some(item => item.link === "https://chatgpt.com");
        if(isDefault) {
            renderFallbackData();
        } else {
            renderCards(windowLastFetchedItems, 'resultsGrid');
        }
    }
    if(currentActiveTab === 'favorites') {
        renderFavorites();
    }
}

document.addEventListener('DOMContentLoaded', () => {
    changeLanguage(currentLang);
    fetchAIData('AI');
    updateFavCount();
});

function updateFavCount() {
    const el = document.getElementById('favCount');
    if(el) el.textContent = favorites.length;
}

function switchTab(tab) {
    currentActiveTab = tab;
    const exploreSec = document.getElementById('exploreSection');
    const favSec = document.getElementById('favoritesSection');
    const submitSec = document.getElementById('submitSection');

    if(exploreSec) exploreSec.classList.add('hidden');
    if(favSec) favSec.classList.add('hidden');
    if(submitSec) submitSec.classList.add('hidden');

    ['explore', 'favorites', 'submit'].forEach(t => {
        const btn = document.getElementById(`tab${t.charAt(0).toUpperCase() + t.slice(1)}`);
        if(btn) {
            if(t === tab) {
                btn.className = "bg-indigo-600 text-white text-xs px-4 py-2 rounded-xl font-semibold transition shadow-md cursor-pointer";
            } else {
                if(t === 'favorites') {
                    btn.className = "bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs px-4 py-2 rounded-xl font-semibold transition flex items-center gap-1.5 cursor-pointer";
                } else {
                    btn.className = "bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs px-4 py-2 rounded-xl font-semibold transition cursor-pointer";
                }
            }
        }
    });

    if(tab === 'explore' && exploreSec) {
        exploreSec.classList.remove('hidden');
    } else if(tab === 'favorites' && favSec) {
        favSec.classList.remove('hidden');
        renderFavorites();
    } else if(tab === 'submit' && submitSec) {
        submitSec.classList.remove('hidden');
    }
}

function setRating(link, stars) {
    ratings[link] = stars;
    localStorage.setItem('semalt_ratings', JSON.stringify(ratings));
    showToast("Rating saved!");
    if(windowLastFetchedItems.length > 0) renderCards(windowLastFetchedItems, 'resultsGrid');
    if(currentActiveTab === 'favorites') renderFavorites();
}

function openPreview(tool) {
    document.getElementById('modalTitle').textContent = tool.title || tool.name;
    document.getElementById('modalDomain').textContent = tryDomain(tool.link);
    document.getElementById('modalSnippet').textContent = tool.snippet || tool.description;
    document.getElementById('modalLinkBtn').href = tool.link;
    document.getElementById('previewModal').classList.remove('hidden');
}

function closePreviewModal() {
    document.getElementById('previewModal').classList.add('hidden');
}

function tryDomain(link) {
    try { return new URL(link).hostname; } catch(e) { return 'ai-tool.com'; }
}

function showToast(msg) {
    const toast = document.getElementById('toast');
    const toastMsg = document.getElementById('toastMsg');
    if(toast && toastMsg) {
        toastMsg.textContent = msg || "Action completed!";
        toast.classList.remove('translate-y-20', 'opacity-0');
        setTimeout(() => { toast.classList.add('translate-y-20', 'opacity-0'); }, 3000);
    }
}

function copyToClipboard(text) {
    navigator.clipboard.writeText(text).then(() => { showToast("Link copied to clipboard!"); });
}

const searchInput = document.getElementById('searchInput');
const resultsGrid = document.getElementById('resultsGrid');
const loading = document.getElementById('loading');

async function fetchAIData(query = 'AI') {
    currentCategory = query;
    if(loading) loading.classList.remove('hidden');
    if(resultsGrid) resultsGrid.innerHTML = '';

    try {
        const apiUrl = `https://freeserp.ai/api.php?index=sites&q=${encodeURIComponent(query)}`;
        const response = await fetch(apiUrl);
        if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
        
        const data = await response.json();
        if(loading) loading.classList.add('hidden');

        let items = Array.isArray(data) ? data : (data.results || data.items || data.data || []);
        
        if(query === 'AI' && customTools.length > 0) {
            items = [...customTools, ...items];
        }

        if (items.length === 0) {
            renderFallbackData();
            return;
        }
        windowLastFetchedItems = items;
        renderCards(items, 'resultsGrid');
    } catch (err) {
        if(loading) loading.classList.add('hidden');
        renderFallbackData();
    }
}

function filterCategory(category, btnElement) {
    document.querySelectorAll('.cat-pill').forEach(btn => {
        btn.className = "cat-pill bg-slate-900 hover:bg-slate-800 border border-slate-800 text-slate-300 text-xs px-4 py-2 rounded-xl font-medium transition cursor-pointer";
    });
    if(btnElement) {
        btnElement.className = "cat-pill bg-indigo-600 text-white text-xs px-4 py-2 rounded-xl font-medium transition shadow-md cursor-pointer";
    }
    fetchAIData(category);
}

function renderCards(items, containerId) {
    const container = document.getElementById(containerId);
    if(!container) return;
    container.innerHTML = '';
    container.className = "grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6";
    const t = translations[currentLang];

    items.forEach((item) => {
        let title = item.title || item.name || 'AI Platform';
        let link = item.link || item.url || '#';
        let snippet = item.snippet || item.description || t.defaultSnippet;
        let domain = tryDomain(link);
        const isFav = favorites.some(f => f.link === link);
        const currentRating = ratings[link] || 4.5;

        const card = document.createElement('div');
        card.className = "bg-slate-900/90 border border-slate-800 rounded-2xl p-5 flex flex-col justify-between hover:border-indigo-500/50 transition duration-300 shadow-xl text-left relative group";
        card.innerHTML = `
            <div>
                <div class="flex justify-between items-start gap-2 mb-3">
                    <span class="bg-indigo-950 text-indigo-300 text-xs px-2.5 py-1 rounded-full border border-indigo-800/50 font-medium truncate max-w-[130px]">
                        <i class="fa-solid fa-globe mr-1"></i> ${domain}
                    </span>
                    <div class="flex items-center gap-2">
                        <button onclick="copyToClipboard('${link}')" class="text-slate-400 hover:text-indigo-400 transition text-sm cursor-pointer" title="Share"><i class="fa-solid fa-share-nodes"></i></button>
                        <button onclick='toggleFavorite(${JSON.stringify({title, link, snippet}).replace(/'/g, "&apos;")})' class="text-slate-400 hover:text-rose-500 transition text-base cursor-pointer">
                            <i class="fa-${isFav ? 'solid text-rose-500' : 'regular'} fa-heart"></i>
                        </button>
                    </div>
                </div>
                <h3 onclick='openPreview(${JSON.stringify({title, link, snippet}).replace(/'/g, "&apos;")})' class="font-bold text-lg mb-2 text-slate-100 line-clamp-1 cursor-pointer hover:underline">${title}</h3>
                <p class="text-slate-400 text-sm mb-4 line-clamp-3 leading-relaxed">${snippet}</p>
            </div>
            <div>
                <div class="flex items-center gap-1 mb-3 text-amber-400 text-xs">
                    ${[1,2,3,4,5].map(star => `<i class="fa-${star <= Math.round(currentRating) ? 'solid' : 'regular'} fa-star cursor-pointer" onclick='setRating("${link}", ${star})'></i>`).join('')}
                    <span class="text-slate-400 ml-1">(${currentRating})</span>
                </div>
                <div class="pt-4 border-t border-slate-800/60 flex items-center justify-between">
                    <button onclick='openPreview(${JSON.stringify({title, link, snippet}).replace(/'/g, "&apos;")})' class="inline-flex items-center text-xs font-semibold text-indigo-400 transition cursor-pointer">
                        ${t.previewBtn} <i class="fa-solid fa-eye ml-1.5 text-[10px]"></i>
                    </button>
                    <a href="${link}" target="_blank" rel="noopener noreferrer" class="text-xs text-slate-400 hover:text-white transition">
                        ${t.visitText} <i class="fa-solid fa-arrow-up-right-from-square text-[10px]"></i>
                    </a>
                </div>
            </div>
        `;
        container.appendChild(card);
    });
}

function renderFallbackData() {
    const t = translations[currentLang];
    const mockData = t.tools;
    const combined = [...customTools, ...mockData];
    windowLastFetchedItems = combined;
    renderCards(combined, 'resultsGrid');
}

function toggleFavorite(tool) {
    const existsIndex = favorites.findIndex(f => f.link === tool.link);
    if(existsIndex >= 0) { favorites.splice(existsIndex, 1); } 
    else { favorites.push(tool); }
    localStorage.setItem('semalt_favs', JSON.stringify(favorites));
    updateFavCount();
    if(windowLastFetchedItems.length > 0) renderCards(windowLastFetchedItems, 'resultsGrid');
    if(currentActiveTab === 'favorites') renderFavorites();
}

function renderFavorites() {
    const favGrid = document.getElementById('favoritesGrid');
    const t = translations[currentLang];
    if(!favGrid) return;
    if(favorites.length === 0) {
        favGrid.innerHTML = `<div class="col-span-full text-center py-20 text-slate-500 text-sm"><i class="fa-regular fa-heart text-3xl mb-2"></i><p>${t.noFavs}</p></div>`;
        return;
    }
    renderCards(favorites, 'favoritesGrid');
}

function handleFormSubmit(event) {
    event.preventDefault();
    const name = document.getElementById('toolName').value;
    const url = document.getElementById('toolUrl').value;
    const desc = document.getElementById('toolDesc').value;

    customTools.unshift({ title: name, link: url, snippet: desc });
    localStorage.setItem('semalt_custom', JSON.stringify(customTools));

    switchTab('explore');
    const successDiv = document.getElementById('formSuccess');
    if(successDiv) {
        successDiv.classList.remove('hidden');
        setTimeout(() => successDiv.classList.add('hidden'), 5000);
    }

    fetchAIData('AI');
    document.getElementById('toolForm').reset();
}

let debounceTimer;
if(searchInput) {
    searchInput.addEventListener('input', (e) => {
        clearTimeout(debounceTimer);
        const query = e.target.value.trim();
        debounceTimer = setTimeout(() => {
            fetchAIData(query.length > 0 ? query : 'AI');
        }, 500);
    });
}